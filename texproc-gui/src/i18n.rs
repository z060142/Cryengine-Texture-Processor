//! Compile-time-complete GUI localization.
//!
//! Every user-visible string is one `&'static str` field on [`Strings`], with a
//! full `EN` and `ZH_CN` instance. Because a missing field is a compile error,
//! adding a language = adding one more `const` instance (no runtime lookup, no
//! JSON, no new dependency). Parameterized messages store a `{}`-placeholder
//! template filled by [`fill`] at the call site.
//!
//! Translation policy (owner ruling T-018): technical terms stay verbatim
//! (diffuse/normal/spec/gloss/DDS/TIF/mtl/CGF/FBX/RC/Metal Gate/setting keys/
//! file names/axis notation). Only operational prose is translated (verbs,
//! buttons, panel titles, status prose, tooltips, error guidance).

/// Selectable GUI language. String forms are `"en"` / `"zh-cn"` (prefs key).
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Language {
    En,
    ZhCn,
}

impl Language {
    /// Parse a prefs code; any unknown value falls back to English.
    pub fn from_code(code: &str) -> Self {
        match code {
            "zh-cn" => Language::ZhCn,
            _ => Language::En,
        }
    }

    /// Canonical prefs string.
    pub fn code(self) -> &'static str {
        match self {
            Language::En => "en",
            Language::ZhCn => "zh-cn",
        }
    }

    /// Native name shown in the language combo (endonym, never translated).
    pub fn endonym(self) -> &'static str {
        match self {
            Language::En => "English",
            Language::ZhCn => "简体中文",
        }
    }

    /// The string table for this language.
    pub fn strings(self) -> &'static Strings {
        match self {
            Language::En => &EN,
            Language::ZhCn => &ZH_CN,
        }
    }
}

/// Fill successive `{}` placeholders in `template` with `args`, in order.
/// Leftover placeholders/args are ignored. There is no brace escaping because
/// no localized template contains a literal `{}`.
pub fn fill(template: &str, args: &[&str]) -> String {
    let mut out = String::with_capacity(template.len());
    let mut args = args.iter();
    let mut chars = template.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '{' && chars.peek() == Some(&'}') {
            chars.next();
            match args.next() {
                Some(arg) => out.push_str(arg),
                None => out.push_str("{}"),
            }
        } else {
            out.push(c);
        }
    }
    out
}

