#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fill_replaces_in_order() {
        assert_eq!(fill("{} of {} groups", &["3", "7"]), "3 of 7 groups");
        assert_eq!(fill("no placeholders", &[]), "no placeholders");
        // Missing arg leaves the placeholder untouched (defensive, not expected).
        assert_eq!(fill("{} and {}", &["a"]), "a and {}");
    }

    #[test]
    fn language_round_trips_and_falls_back() {
        assert_eq!(Language::from_code("en"), Language::En);
        assert_eq!(Language::from_code("zh-cn"), Language::ZhCn);
        assert_eq!(Language::from_code("fr"), Language::En);
        assert_eq!(Language::from_code(""), Language::En);
        assert_eq!(Language::En.code(), "en");
        assert_eq!(Language::ZhCn.code(), "zh-cn");
    }
}
